/** تولیدِ کلیدِ یکتا برایِ هر اقدامِ صف‌شده -- طبقِ تصمیمِ طراحیِ
 * آفلاین (سندِ معماریِ پخشِ سرد/گرم): هر اقدامِ درصف باید یک کلیدِ
 * یکتایِ پایدار داشته باشد تا اگر ارسال دوباره تلاش شود (مثلاً بعدِ
 * قطعیِ نیمه‌کاره‌یِ شبکه)، بشود تشخیص داد قبلاً ارسال شده یا نه.
 *
 * نکته‌یِ مهم/محدودیتِ شناخته‌شده: اندپوینت‌هایِ فعلیِ peecha_api
 * (R131) هنوز این کلید را در سمتِ سرور بررسی/دیدوپلیکیت نمی‌کنند --
 * یعنی اگر یک اقدام واقعاً رویِ سرور موفق شده باشد ولی پاسخ به دلیلِ
 * قطعیِ شبکه به کلاینت نرسیده باشد، تلاشِ دوباره ممکن است یک رکوردِ
 * تکراری بسازد. رفعِ این شکاف (افزودنِ جدولِ idempotency_keys در
 * peecha_api و بررسیِ آن پیش از اجرا) بخشی از کارِ R133 است.
 */
export function generateIdempotencyKey(): string {
  const random = Math.random().toString(36).slice(2);
  const time = Date.now().toString(36);
  return `${time}-${random}`;
}
