def _merge_source_strings() -> dict[str, str]:
    """فهرستِ SOURCE_STRINGس این ماژول را با هر چیزِ دیگری که هنگامِ اجرا
    ثبت شده یکی می‌کند — تا هیچ‌کدام از این دو منبع رشته‌ای را گم نکند."""
    source = i18n._load_source_catalog()  # noqa: SLF001 - همین ماژول مسئولِ نگه‌داریِ فهرستِ منبع است
    changed = False
    for text in SOURCE_STRINGS:
        if text not in source:
            source[text] = text
            changed = True
    if changed:
        i18n._write_json(i18n._SOURCE_CATALOG_PATH, source)  # noqa: SLF001
    return source


def generate_translation_file(language_code: str) -> None:
    """فایلِ ترجمه‌ی یک زبان را می‌سازد/تکمیل می‌کند — طبق درخواستِ صریح،
    هنگامِ ساختِ زبانِ تازه صدا زده می‌شود. برای زبان‌هایی که در
    KNOWN_TRANSLATIONS نیستند، مقدارها همان فارسیِ منبع می‌مانند (آماده‌ی
    اصلاحِ دستی در همان فایل).

    نکته‌ی مهم: این تابع فقط رشته‌های *گم‌شده* را اضافه می‌کند، نه این‌که
    کلِ فایل را از نو بسازد — چون این تابع هر بار بالا آمدنِ برنامه دوباره
    صدا زده می‌شود (نگاه کن به shell.py::_sync_translation_files)، اگر
    کاتالوگِ موجود را بازنویسی می‌کرد، هر ترجمه‌ی دستی یا آنلاینِ کاربر با
    هر ری‌استارت پاک می‌شد."""
    source = _merge_source_strings()
    known = KNOWN_TRANSLATIONS.get(language_code, {})
    existing = i18n._load_catalog(language_code)  # noqa: SLF001
    catalog = dict(existing)
    changed = False
    for text in source:
        if text not in catalog:
            catalog[text] = known.get(text, text)
            changed = True
    if not changed:
        return
    i18n._write_json(i18n._catalog_path(language_code), catalog)  # noqa: SLF001
    i18n.invalidate_cache(language_code)


def regenerate_all(language_codes: list[str]) -> None:
    """طبق درخواستِ صریح («در آینده هم اگر فرمی اضافه میشه ترجمه بشه»):
    وقتی رشته‌ی تازه‌ای به SOURCE_STRINGS اضافه شود، این تابع فایلِ همه‌ی
    زبان‌های موجود را دوباره می‌سازد تا رشته‌ی تازه در همه‌شان ظاهر شود."""
    for code in language_codes:
        generate_translation_file(code)
