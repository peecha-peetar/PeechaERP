-- طبقِ گزارشِ کاربر («عکس و امضایِ ویزیت کجا ذخیره می‌شود؟ الان معلوم
-- نیست»): تا امروز photo_base64 مستقیماً به‌صورتِ رشتهٔ base64 در
-- خودِ ستونِ دیتابیس ذخیره می‌شد -- برخلافِ الگویِ استانداردِ همین
-- پروژه (delivery_confirmations، پیوست‌هایِ detail_dimensions) که
-- فایل رویِ دیسک ذخیره و فقط مسیرش در دیتابیس رفرنس می‌شود. این
-- مهاجرت آن ناسازگاری را رفع می‌کند: photo_storage_key جایگزینِ
-- photo_base64 می‌شود، و signature_storage_key هم اضافه می‌شود چون
-- امضا برایِ ویزیتِ عمومی (برخلافِ تاییدِ تحویل) اصلاً وجود نداشت.
-- دادهٔ قدیمیِ این ستون (اگر در محیطی واقعاً استفاده شده باشد) قابلِ
-- بازیابی نیست -- طبقِ وضعیتِ فعلیِ پروژه (پیشِ‌راه‌اندازی، بدونِ
-- دادهٔ واقعیِ مشتری) قابلِ‌قبول است.

ALTER TABLE comm.customer_visits
    DROP COLUMN photo_base64,
    ADD COLUMN photo_storage_key TEXT,
    ADD COLUMN signature_storage_key TEXT;
