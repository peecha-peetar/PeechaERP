-- طبقِ گزارشِ صریح («فیلدهایِ تخصصیِ حساب‌هایِ تفصیلی در سطحِ اول باز
-- نمی‌شوند»): پیش‌فرضِ max_level_no=4 برایِ گروه‌هایِ سیستمی (بانک/صندوق/
-- تنخواه/مرکزِ هزینه/پروژه/مرکزِ سود/دارایی‌ثابت — همه به‌جز کالا که قبلاً
-- در 080_inventory_item_default_level.sql رفع شد) و هر گروهِ تفصیلیِ
-- سفارشیِ دیگر، باعث می‌شد فیلدهایِ اختصاصیِ آن‌ها هرگز در سطحِ ۱ (که در
-- عملِ اکثرِ شرکت‌ها همان تنها/آخرین سطح است) نمایش داده نشوند. این پیش‌فرض
-- برایِ رکوردهایِ موجود که هنوز رویِ همان مقدارِ پیش‌فرضِ دست‌نخورده‌اند
-- بازنشانی می‌شود؛ گروه‌هایی که مدیر عمداً سطح‌بندیِ چندگانه برایشان تنظیم
-- کرده (max_level_no <> 4) دست‌نخورده می‌مانند.
UPDATE acc.detail_dimension_types
SET max_level_no = 1
WHERE code <> 'INVENTORY_ITEM' AND max_level_no = 4;
